/*
 * ============================================================================
 *  03. СОРТИРОВКА ПОДСЧЁТОМ (counting sort)
 *  Кормен 8.2
 *  Запуск: g++ -std=c++17 -O2 -Wall -Wextra 03_counting_sort.cpp -o cnt && ./cnt
 * ============================================================================
 *
 *  Когда применять: ЦЕЛЫЕ числа из НЕБОЛЬШОГО диапазона [mn, mx].
 *  k = mx - mn + 1 — размер диапазона.
 *  Время O(n + k), память O(n + k). НЕ сравнивает элементы -> нижняя граница
 *  Ω(n log n) на неё не действует.
 *
 *  Если k огромный (например, числа до 1e18) — массив cnt не поместится в память.
 *  Тогда нужна поразрядная сортировка (04_radix_sort.cpp).
 *
 *  Три версии:
 *    1. countingSortSimple — только числа, самая короткая
 *    2. countingSort       — стабильная, как на доске (исправленная)
 *    3. countingSortByKey  — стабильная сортировка ОБЪЕКТОВ по целому ключу
 *                            (именно так она используется внутри radix sort)
 */

#include <algorithm>
#include <cassert>
#include <iostream>
#include <random>
#include <string>
#include <vector>

using namespace std;

// ============================================================================
// 1. ПРОСТАЯ ВЕРСИЯ
// Считаем, сколько раз встретилось каждое значение, потом выписываем подряд.
// Минус: работает только для "голых" чисел. Если у числа есть привязанные данные
// (имя студента и т.п.), они потеряются — мы же создаём числа заново.
// ============================================================================
void countingSortSimple(vector<int>& a) {
    if (a.empty()) return;  // иначе *min_element на пустом массиве — неопределённое поведение (UB)

    int mn = *min_element(a.begin(), a.end());
    int mx = *max_element(a.begin(), a.end());

    // cnt[v] = сколько раз встретилось значение (v + mn).
    // Сдвиг на mn позволяет сортировать отрицательные числа и не тратить память на [0, mn).
    // РАЗМЕР mx - mn + 1 (а не mx - mn!) — значения от mn до mx включительно.
    vector<int> cnt(mx - mn + 1, 0);
    for (int x : a) cnt[x - mn]++;

    int pos = 0;
    for (int v = 0; v < (int)cnt.size(); ++v) {
        for (int c = 0; c < cnt[v]; ++c) {
            a[pos++] = v + mn;
        }
    }
}

// ============================================================================
// 2. СТАБИЛЬНАЯ ВЕРСИЯ (как на доске, но исправленная — см. 99_code_review.md)
//
// Шаг 1. cnt[v] = количество элементов со значением v
// Шаг 2. префиксные суммы: cnt[v] = количество элементов со значением <= v.
//        Значит элементы со значением v должны занять позиции
//        [cnt[v-1], cnt[v]) в ответе, и ПОСЛЕДНИЙ из них — позицию cnt[v] - 1.
// Шаг 3. идём по исходному массиву С КОНЦА, каждый элемент ставим на позицию
//        --cnt[v] (сначала уменьшили, потом используем как индекс).
//        Так последний элемент со значением v встанет на последнее место своего блока,
//        предпоследний — перед ним, ... -> порядок равных сохранён = СТАБИЛЬНОСТЬ.
//
// Пример: a = [3, 1, 3, 0, 1], mn = 0, mx = 3
//   шаг 1: cnt = [1, 2, 0, 2]        (одна 0, две 1, ноль 2, две 3)
//   шаг 2: cnt = [1, 3, 3, 5]        (<=0: 1, <=1: 3, <=2: 3, <=3: 5)
//   шаг 3: i=4: a[4]=1 -> --cnt[1]=2 -> ans[2]=1   cnt=[1,2,3,5]
//          i=3: a[3]=0 -> --cnt[0]=0 -> ans[0]=0   cnt=[0,2,3,5]
//          i=2: a[2]=3 -> --cnt[3]=4 -> ans[4]=3   cnt=[0,2,3,4]
//          i=1: a[1]=1 -> --cnt[1]=1 -> ans[1]=1   cnt=[0,1,3,4]
//          i=0: a[0]=3 -> --cnt[3]=3 -> ans[3]=3   cnt=[0,1,3,3]
//   ans = [0, 1, 1, 3, 3]
// ============================================================================
// const vector<int>& a — читаем, но не меняем; результат возвращаем новым вектором
vector<int> countingSort(const vector<int>& a) {
    if (a.empty()) return {};  // {} — пустой vector<int>

    int mn = *min_element(a.begin(), a.end());
    int mx = *max_element(a.begin(), a.end());
    int k = mx - mn + 1;
    int n = (int)a.size();

    vector<int> cnt(k, 0);
    for (int x : a) cnt[x - mn]++;

    for (int v = 1; v < k; ++v) cnt[v] += cnt[v - 1];

    vector<int> ans(n);
    for (int i = n - 1; i >= 0; --i) {  // int, а не size_t: иначе i >= 0 всегда true
        ans[--cnt[a[i] - mn]] = a[i];
    }
    return ans;
}

// ============================================================================
// 3. СТАБИЛЬНАЯ СОРТИРОВКА ОБЪЕКТОВ ПО КЛЮЧУ
// Сортируем студентов по оценке 2..5. Студенты с одинаковой оценкой должны
// остаться в исходном порядке (например, исходно были отсортированы по фамилии).
// Здесь ключи маленькие и известны заранее, min/max можно не искать.
// ============================================================================
struct Student {
    string name;
    int grade;  // от 0 до MAX_GRADE
};

const int MAX_GRADE = 5;

vector<Student> countingSortByKey(const vector<Student>& a) {
    vector<int> cnt(MAX_GRADE + 1, 0);
    for (const Student& s : a) cnt[s.grade]++;

    // Другой способ стабильно раскладывать: превращаем cnt в "позицию НАЧАЛА блока"
    // и идём по массиву С НАЧАЛА. Это тоже стабильно.
    // start[v] = количество элементов со значением < v
    int sum = 0;
    for (int v = 0; v <= MAX_GRADE; ++v) {
        int c = cnt[v];
        cnt[v] = sum;  // теперь cnt[v] — первая свободная позиция блока v
        sum += c;
    }

    vector<Student> ans(a.size());
    for (const Student& s : a) {
        ans[cnt[s.grade]++] = s;  // кладём на первое свободное место блока и сдвигаем его
    }
    return ans;
}

// ============================================================================
// ТЕСТЫ
// ============================================================================
int main() {
    mt19937 rng(42);

    for (int iter = 0; iter < 1000; ++iter) {
        int n = rng() % 100;
        vector<int> a(n);
        for (int& x : a) x = (int)(rng() % 2001) - 1000;  // с отрицательными
        vector<int> expected = a;
        sort(expected.begin(), expected.end());

        vector<int> b = a;
        countingSortSimple(b);
        assert(b == expected);
        assert(countingSort(a) == expected);
    }
    cout << "countingSort (с отрицательными): OK\n";

    vector<Student> st = {{"Аня", 5}, {"Боря", 3}, {"Вика", 5}, {"Гоша", 4}, {"Даша", 3}};
    vector<Student> sorted = countingSortByKey(st);
    // Ожидаем: Боря 3, Даша 3, Гоша 4, Аня 5, Вика 5 (внутри оценки — исходный порядок)
    vector<string> expectedNames = {"Боря", "Даша", "Гоша", "Аня", "Вика"};
    for (int i = 0; i < (int)sorted.size(); ++i) {
        assert(sorted[i].name == expectedNames[i]);
    }
    cout << "countingSortByKey (стабильность): OK\n";

    // Большой тест: 1e7 чисел из [0, 1000] — сортировка подсчётом тут намного быстрее std::sort
    vector<int> big(10'000'000);
    for (int& x : big) x = rng() % 1001;
    countingSortSimple(big);
    assert(is_sorted(big.begin(), big.end()));
    cout << "1e7 элементов: OK\n";
}
