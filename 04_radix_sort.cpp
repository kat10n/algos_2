/*
 * ============================================================================
 *  04. ПОРАЗРЯДНАЯ СОРТИРОВКА (radix sort, LSD)
 *  Кормен 8.3, Седжвик гл. 10
 *  Запуск: g++ -std=c++17 -O2 -Wall -Wextra 04_radix_sort.cpp -o radix && ./radix
 * ============================================================================
 *
 *  Проблема counting sort: числа до 1e18 -> массив cnt на 1e18 ячеек невозможен.
 *  Идея radix: представить число как d "цифр" по основанию b и сортировать
 *  по одной цифре за раз — каждый проход это counting sort с k = b.
 *
 *  LSD (Least Significant Digit) — от МЛАДШЕЙ цифры к старшей.
 *
 *  Пример (основание 10): [170, 45, 75, 90, 802, 24, 2, 66]
 *    по единицам:  [170, 90, 802, 2, 24, 45, 75, 66]
 *    по десяткам:  [802, 2, 24, 45, 66, 170, 75, 90]
 *    по сотням:    [2, 24, 45, 66, 75, 90, 170, 802]  <- готово
 *
 *  ПОЧЕМУ ЭТО РАБОТАЕТ (доказательство по индукции):
 *    Утверждение: после прохода по разряду i массив отсортирован по
 *    числу, составленному из младших i+1 цифр.
 *    Переход: сортируем по цифре i. Если цифры i у двух чисел разные —
 *    их порядок определяет эта цифра (правильно). Если одинаковые — порядок
 *    определяют младшие цифры, а он уже правильный с прошлого шага и
 *    СОХРАНИТСЯ, потому что counting sort СТАБИЛЬНЫЙ.
 *    => без стабильности radix sort не работает!
 *
 *  Сложность: O(d * (n + b)), d — число цифр, b — основание.
 *    Основание 10, числа до 1e9: d = 10 проходов.
 *    Основание 256 (байты), uint32: d = 4 прохода. uint64: d = 8.
 *  Выбор b — компромисс: больше b -> меньше проходов, но массив cnt больше
 *  (b = 2^16 -> cnt на 65536 элементов, уже не влезает в кэш L1).
 *  На практике b = 256 — лучший вариант.
 *
 *  Вместо деления и % по основанию 256 используем биты:
 *    (x >> 8*i) & 255 — i-й байт числа (сдвиг вправо = деление на 2^(8i),
 *    & 255 = остаток от деления на 256). Это намного быстрее, чем / и %.
 */

#include <algorithm>
#include <array>
#include <cassert>
#include <cstdint>
#include <iostream>
#include <random>
#include <vector>

using namespace std;

// ============================================================================
// 1. ОСНОВАНИЕ 10 — версия с доски (исправленная), для НЕОТРИЦАТЕЛЬНЫХ int
// ============================================================================

// Один проход: стабильная сортировка подсчётом по цифре (x / exp) % 10.
// exp = 1 -> единицы, 10 -> десятки, 100 -> сотни ...
void countingByDigit(vector<int>& a, long long exp) {
    int n = (int)a.size();
    array<int, 10> cnt{};  // {} обнуляет. array — массив фиксированного размера (00_cpp_basics п.11)

    for (int x : a) cnt[(x / exp) % 10]++;
    for (int d = 1; d < 10; ++d) cnt[d] += cnt[d - 1];

    vector<int> out(n);
    for (int i = n - 1; i >= 0; --i) {       // с конца — ради стабильности
        int digit = (a[i] / exp) % 10;
        out[--cnt[digit]] = a[i];
    }
    a.swap(out);  // O(1) обмен вместо копирования a = out
}

void radixSort10(vector<int>& a) {
    if (a.empty()) return;
    int mx = *max_element(a.begin(), a.end());
    // exp — long long: если mx ~ 2e9, то exp дойдёт до 1e10 и в int бы переполнился
    for (long long exp = 1; mx / exp > 0; exp *= 10) {
        countingByDigit(a, exp);
    }
}

// ============================================================================
// 2. ОСНОВАНИЕ 256 для uint64_t — быстрая версия
// ============================================================================
void radixSort256(vector<uint64_t>& a) {
    if (a.empty()) return;
    size_t n = a.size();
    vector<uint64_t> buf(n);
    uint64_t mx = *max_element(a.begin(), a.end());

    // shift = 0, 8, 16, ..., 56 — номер байта * 8.
    // Условие (mx >> shift) > 0: если у максимума старшие байты нулевые,
    // то и у всех остальных тоже — такие проходы ничего не меняют, пропускаем.
    for (int shift = 0; shift < 64 && (mx >> shift) > 0; shift += 8) {
        array<size_t, 256> cnt{};
        for (uint64_t x : a) cnt[(x >> shift) & 255]++;

        // превращаем в позиции начала блоков (как в 03, версия 3) и идём СПЕРЕДИ
        size_t sum = 0;
        for (size_t d = 0; d < 256; ++d) {
            size_t c = cnt[d];
            cnt[d] = sum;
            sum += c;
        }
        for (uint64_t x : a) buf[cnt[(x >> shift) & 255]++] = x;

        a.swap(buf);  // теперь a — результат прохода, buf — старые данные (перезапишем)
    }
}

// ============================================================================
// 3. ОТРИЦАТЕЛЬНЫЕ ЧИСЛА (int64_t)
// Отрицательные хранятся в дополнительном коде: у них старший бит = 1,
// поэтому как беззнаковые они выглядят БОЛЬШЕ положительных.
// Трюк: инвертировать старший (знаковый) бит.
//   -5  -> старший бит был 1, станет 0 -> маленькое беззнаковое
//    5  -> старший бит был 0, станет 1 -> большое беззнаковое
// Внутри отрицательных и внутри положительных порядок сохраняется.
// ============================================================================
void radixSortSigned(vector<int64_t>& a) {
    const uint64_t SIGN = 1ULL << 63;   // 1ULL — единица типа unsigned long long, иначе сдвиг на 63 переполнит int
    vector<uint64_t> u(a.size());
    for (size_t i = 0; i < a.size(); ++i) u[i] = (uint64_t)a[i] ^ SIGN;  // ^ — XOR, переключает бит
    radixSort256(u);
    for (size_t i = 0; i < a.size(); ++i) a[i] = (int64_t)(u[i] ^ SIGN);
}

// ============================================================================
// Замечание про MSD (Most Significant Digit) — от старшей цифры:
// раскладываем по старшей цифре на корзины, потом рекурсивно сортируем каждую
// корзину по следующей цифре. Удобна для строк разной длины (сортировка
// словаря): можно остановиться, когда корзина из 1 элемента. Сложнее в реализации.
// ============================================================================

int main() {
    mt19937_64 rng(7);  // 64-битный генератор

    for (int iter = 0; iter < 500; ++iter) {
        int n = rng() % 200;
        vector<int> a(n);
        for (int& x : a) x = rng() % 2'000'000'000;  // до 2e9 — проверяем exp без переполнения
        vector<int> e = a;
        sort(e.begin(), e.end());
        radixSort10(a);
        assert(a == e);
    }
    cout << "radixSort10: OK\n";

    for (int iter = 0; iter < 500; ++iter) {
        int n = rng() % 200;
        vector<uint64_t> a(n);
        for (auto& x : a) x = rng() >> (rng() % 64);  // числа разной длины
        vector<uint64_t> e = a;
        sort(e.begin(), e.end());
        radixSort256(a);
        assert(a == e);
    }
    cout << "radixSort256: OK\n";

    for (int iter = 0; iter < 500; ++iter) {
        int n = rng() % 200;
        vector<int64_t> a(n);
        for (auto& x : a) x = (int64_t)rng();  // и отрицательные, и положительные
        vector<int64_t> e = a;
        sort(e.begin(), e.end());
        radixSortSigned(a);
        assert(a == e);
    }
    cout << "radixSortSigned: OK\n";
}
